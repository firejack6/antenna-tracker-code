def _prompt(label: str, current: str, *, secret: bool = False) -> str:
    shown = current
    if secret and current:
        shown = "*" * min(8, len(current)) + ("…" if len(current) > 8 else "")
    suffix = f" [{shown}]" if shown != "" else ""
    try:
        typed = input(f"{label}{suffix}: ").strip()
    except EOFError:
        return current
    return typed if typed != "" else current


def prompt_all(current: dict[str, str]) -> dict[str, str]:
    print("Antenna-tracker local setup (.env). Enter to keep the value in brackets.\n")
    out = dict(current)
    out["WIFI_SSID"] = _prompt("Wi-Fi SSID", current.get("WIFI_SSID", ""))
    out["WIFI_PASSWORD"] = _prompt("Wi-Fi password (≥8 chars)", current.get("WIFI_PASSWORD", ""), secret=True)
    ap = _prompt("Wi-Fi access-point mode? (true/false)", current.get("WIFI_ACCESS_POINT", "true"))
    out["WIFI_ACCESS_POINT"] = "true" if ap.lower() in ("1", "true", "yes", "y", "on") else "false"
    print()
    out["OPENSKY_CLIENT_ID"] = _prompt("OpenSky client id", current.get("OPENSKY_CLIENT_ID", ""))
    out["OPENSKY_CLIENT_SECRET"] = _prompt(
        "OpenSky client secret (blank keeps existing file secret on --apply)",
        current.get("OPENSKY_CLIENT_SECRET", ""),
        secret=True,
    )
    print()
    out["SITE_ID"] = _prompt("Site id", current.get("SITE_ID", "home"))
    out["SITE_LABEL"] = _prompt("Site label", current.get("SITE_LABEL", "home"))
    out["SITE_LAT"] = _prompt("Site latitude (blank = skip sites.json)", current.get("SITE_LAT", ""))
    out["SITE_LON"] = _prompt("Site longitude", current.get("SITE_LON", ""))
    out["SITE_ALT"] = _prompt("Site altitude m", current.get("SITE_ALT", "0"))
    print()
    out["ADSB_HOST"] = _prompt("ADS-B dump1090 host IP", current.get("ADSB_HOST", "127.0.0.1"))
    out["ADSB_PORT"] = _prompt("ADS-B HTTP port", current.get("ADSB_PORT", "8080"))
    out["ADSB_POLL_INTERVAL"] = _prompt("ADS-B poll interval s (0.5 = 2 Hz)", current.get("ADSB_POLL_INTERVAL", "0.5"))
    out["ESP_TCP"] = _prompt("ESP TCP endpoint", current.get("ESP_TCP", "192.168.20.1:9000"))
    return out


def _cpp_string(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def apply_network_config(values: dict[str, str]) -> str:
    if not NETWORK_CONFIG.is_file():
        return f"skip network_config.h (missing {NETWORK_CONFIG})"
    text = NETWORK_CONFIG.read_text(encoding="utf-8")
    ssid = _cpp_string(values.get("WIFI_SSID") or "antenna-tracker")
    password = values.get("WIFI_PASSWORD") or ""
    if len(password) < 8:
        return "skip network_config.h (WIFI_PASSWORD must be ≥ 8 characters)"
    password = _cpp_string(password)
    ap = (values.get("WIFI_ACCESS_POINT") or "true").lower() in ("1", "true", "yes", "y", "on")
    text2, n1 = re.subn(
        r'constexpr char WIFI_SSID\[\] = "[^"]*";',
        f'constexpr char WIFI_SSID[] = "{ssid}";',
        text,
        count=1,
    )
    text2, n2 = re.subn(
        r'constexpr char WIFI_PASSWORD\[\] = "[^"]*";',
        f'constexpr char WIFI_PASSWORD[] = "{password}";',
        text2,
        count=1,
    )
    text2, n3 = re.subn(
        r"constexpr bool WIFI_ACCESS_POINT = (true|false);",
        f"constexpr bool WIFI_ACCESS_POINT = {'true' if ap else 'false'};",
        text2,
        count=1,
    )
    if n1 + n2 + n3 == 0:
        return "skip network_config.h (patterns not found)"
    NETWORK_CONFIG.write_text(text2, encoding="utf-8")
    return f"updated {NETWORK_CONFIG.relative_to(ROOT)} (re-flash firmware for Wi-Fi)"


def apply_opensky(values: dict[str, str]) -> str:
    sys.path.insert(0, str(DASHBOARD))
    from opensky_config import load_credentials, save_credentials  # noqa: WPS433

    cid = (values.get("OPENSKY_CLIENT_ID") or "").strip() or "your-opensky-client-id"
    secret = values.get("OPENSKY_CLIENT_SECRET")
    if secret is None or secret == "":
        # Keep existing secret if prompt left blank and file already has one.
        existing = load_credentials().get("client_secret") or ""
        if existing:
            save_credentials(cid, None)
            return f"updated {OPENSKY_CREDS.relative_to(ROOT)} (kept existing secret)"
        save_credentials(cid, "")
        return f"updated {OPENSKY_CREDS.relative_to(ROOT)} (no secret yet)"
    save_credentials(cid, secret)
    return f"updated {OPENSKY_CREDS.relative_to(ROOT)}"


def apply_sites(values: dict[str, str]) -> str:
    lat_s = (values.get("SITE_LAT") or "").strip()
    lon_s = (values.get("SITE_LON") or "").strip()
    if not lat_s or not lon_s:
        return "skip sites.json (SITE_LAT / SITE_LON blank)"
    try:
        lat = float(lat_s)
        lon = float(lon_s)
        alt = float(values.get("SITE_ALT") or 0)
    except ValueError:
        return "skip sites.json (lat/lon/alt not numeric)"
    if abs(lat) > 90 or abs(lon) > 180:
        return "skip sites.json (lat/lon out of range)"

    SITES_PATH.parent.mkdir(parents=True, exist_ok=True)
    sites: list[dict] = []
    if SITES_PATH.is_file():
        try:
            raw = json.loads(SITES_PATH.read_text(encoding="utf-8"))
            sites = list(raw.get("sites") or [])
        except (OSError, TypeError, ValueError, json.JSONDecodeError):
            sites = []

    sid = (values.get("SITE_ID") or "home").strip() or "home"
    label = (values.get("SITE_LABEL") or sid).strip() or sid
    site = {"id": sid, "label": label, "lat": lat, "lon": lon, "alt": alt, "notes": ""}
    replaced = False
    for i, item in enumerate(sites):
        if isinstance(item, dict) and str(item.get("id") or "") == sid:
            sites[i] = site
            replaced = True
            break
    if not replaced:
        sites.insert(0, site)
    SITES_PATH.write_text(json.dumps({"sites": sites}, indent=2) + "\n", encoding="utf-8")
    return f"updated {SITES_PATH.relative_to(ROOT)}"


def apply_local_defaults(values: dict[str, str]) -> str:
    try:
        port = int(float(values.get("ADSB_PORT") or 8080))
        interval = float(values.get("ADSB_POLL_INTERVAL") or 0.5)
    except ValueError:
        port, interval = 8080, 0.5
    payload = {
        "adsb_host": (values.get("ADSB_HOST") or "127.0.0.1").strip(),
        "adsb_port": port,
        "adsb_poll_interval": interval,
        "esp_tcp": (values.get("ESP_TCP") or "192.168.20.1:9000").strip(),
        "opensky_client_id": (values.get("OPENSKY_CLIENT_ID") or "").strip(),
    }
    LOCAL_DEFAULTS.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    return f"updated {LOCAL_DEFAULTS.relative_to(ROOT)}"


def apply_all(values: dict[str, str]) -> list[str]:
    return [
        apply_network_config(values),
        apply_opensky(values),
        apply_sites(values),
        apply_local_defaults(values),
    ]


def write_example() -> None:
    write_dotenv(EXAMPLE_PATH, DEFAULTS)
    print(f"Wrote {EXAMPLE_PATH.relative_to(ROOT)}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Set up antenna-tracker .env and local config files")
    parser.add_argument("--apply", action="store_true", help="Apply existing .env without prompts")
    parser.add_argument("--example", action="store_true", help="Rewrite .env.example only")
    parser.add_argument("--env", type=Path, default=ENV_PATH, help="Path to .env (default: antenna-tracker/.env)")
    args = parser.parse_args(argv)

    if args.example:
        write_example()
        return 0

    env_path: Path = args.env
    current = load_dotenv(env_path)
    if args.apply:
        if not env_path.is_file():
            print(f"No {env_path} — run without --apply first, or copy .env.example → .env", file=sys.stderr)
            return 1
        values = current
    else:
        # Seed prompts from existing .env, then OpenSky JSON / sites if present.
        if OPENSKY_CREDS.is_file():
            try:
                sys.path.insert(0, str(DASHBOARD))
                from opensky_config import load_credentials  # noqa: WPS433
                creds = load_credentials()
                if creds.get("client_id") and current.get("OPENSKY_CLIENT_ID") in ("", "your-opensky-client-id"):
                    current["OPENSKY_CLIENT_ID"] = creds["client_id"]
                if creds.get("client_secret") and not current.get("OPENSKY_CLIENT_SECRET"):
                    current["OPENSKY_CLIENT_SECRET"] = creds["client_secret"]
            except Exception:
                pass
        if SITES_PATH.is_file() and not current.get("SITE_LAT"):
            try:
                sites = json.loads(SITES_PATH.read_text(encoding="utf-8")).get("sites") or []
                if sites and isinstance(sites[0], dict):
                    s0 = sites[0]
                    current["SITE_ID"] = str(s0.get("id") or current.get("SITE_ID") or "home")
                    current["SITE_LABEL"] = str(s0.get("label") or current.get("SITE_LABEL") or "home")
                    if s0.get("lat") is not None:
                        current["SITE_LAT"] = str(s0["lat"])
                    if s0.get("lon") is not None:
                        current["SITE_LON"] = str(s0["lon"])
                    if s0.get("alt") is not None:
                        current["SITE_ALT"] = str(s0["alt"])
            except Exception:
                pass
        values = prompt_all(current)

    write_dotenv(env_path, values)
    print(f"\nWrote {env_path}")
    print("Applying…")
    for note in apply_all(values):
        print(f"  · {note}")
    print("\nDone. OpenSky/ADS-B pick up JSON on next relay start; Wi-Fi needs a firmware flash.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
